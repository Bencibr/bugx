#!/usr/bin/env python3
"""Engine-owned Finding verification with two independent executions.

Worker checkpoints may contain candidate declarations and receipts, but they
never become verification authority.  This module accepts a host supplied,
pre-registered recipe, executes its positive case twice and its fixed negative
control once, then records the raw outputs and hashes generated by the engine.
"""

from __future__ import annotations

import hashlib
import json
import math
import os
import tempfile
import time
import uuid
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Mapping, Sequence

from core.supervisor.worker_execution import run_bounded, WorkerExecutionError


PROTOCOL_VERSION = 2
MAX_RECIPE_BYTES = 128 * 1024
MAX_OUTPUT_BYTES = 2 * 1024 * 1024
MAX_TIMEOUT_SECONDS = 900.0
POSITIVE_RUNS_REQUIRED = 2


class VerificationError(ValueError):
    """Recipe, binding or execution record failed closed validation."""


class VerificationBlocked(VerificationError):
    """The requested execution cannot be provided safely on this platform."""


def _canonical(value: object) -> bytes:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"), allow_nan=False).encode("utf-8")


def _sha256(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def _text(value: object, field: str, *, max_length: int = 4096) -> str:
    if not isinstance(value, str) or not value.strip() or len(value) > max_length:
        raise VerificationError(f"{field} 必须是非空字符串")
    return value.strip()


def _argv(value: object, field: str) -> list[str]:
    if isinstance(value, (str, bytes)) or not isinstance(value, Sequence):
        raise VerificationError(f"{field} 必须是 argv 数组，禁止 shell 字符串")
    result = list(value)
    if not result or len(result) > 256 or any(not isinstance(item, str) or not item for item in result):
        raise VerificationError(f"{field} 必须是非空字符串数组")
    if any(any(token in item for token in (";", "&&", "||", "`", "$(", ">", "<")) for item in result):
        raise VerificationError(f"{field} 不能包含 shell 运算符")
    return result


def _finite_number(value: object, field: str, *, minimum: float = 0.0, maximum: float | None = None) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise VerificationError(f"{field} 必须是数字")
    value = float(value)
    if not math.isfinite(value) or value < minimum or (maximum is not None and value > maximum):
        raise VerificationError(f"{field} 超出范围")
    return value


def _relative_cwd(root: Path, value: object) -> Path:
    raw = _text(value, "cwd", max_length=1024)
    candidate = Path(raw)
    if candidate.is_absolute():
        raise VerificationError("recipe.cwd 必须是相对项目根路径")
    resolved_root = root.resolve()
    lexical = resolved_root / candidate
    # Reject a symlinked cwd before resolving it; resolving first would erase
    # the evidence and turn an escape into an apparently confined directory.
    cursor = resolved_root
    for part in candidate.parts:
        if part in {"", "."}:
            continue
        cursor = cursor / part
        if cursor.is_symlink():
            raise VerificationError("recipe.cwd 不能穿过符号链接")
    resolved = lexical.resolve()
    try:
        resolved.relative_to(resolved_root)
    except ValueError as exc:
        raise VerificationError("recipe.cwd 越界") from exc
    if not resolved.is_dir() or resolved.is_symlink():
        raise VerificationError("recipe.cwd 不是安全目录")
    return resolved


def _oracle_case(value: object, field: str) -> dict[str, object]:
    if not isinstance(value, Mapping):
        raise VerificationError(f"{field} 必须是对象")
    kind = _text(value.get("kind", value.get("type", "exit_code")), f"{field}.kind", max_length=64)
    if kind not in {"exit_code", "stdout_contains", "json"}:
        raise VerificationError(f"{field}.kind 不支持: {kind}")
    normalized = dict(value)
    normalized["kind"] = kind
    if kind == "exit_code":
        expected = value.get("expected_exit_code", value.get("exit_code"))
        if isinstance(expected, bool) or not isinstance(expected, int) or expected < -255 or expected > 255:
            raise VerificationError(f"{field}.expected_exit_code 无效")
        normalized["expected_exit_code"] = expected
    elif kind == "stdout_contains":
        normalized["text"] = _text(value.get("text"), f"{field}.text", max_length=1024)
    else:
        normalized["path"] = _text(value.get("path"), f"{field}.path", max_length=256)
        normalized["equals"] = value.get("equals")
    return normalized


@dataclass(frozen=True)
class VerificationRecipe:
    """Validated immutable recipe used for all positive/control executions."""

    positive_argv: tuple[str, ...]
    negative_argv: tuple[str, ...]
    cwd: Path
    positive_oracle: Mapping[str, object]
    negative_oracle: Mapping[str, object]
    timeout_seconds: float
    oracle_reference: str
    oracle_hash: str
    input_digest: str | None = None

    @classmethod
    def from_mapping(cls, root: Path, payload: Mapping[str, object]) -> "VerificationRecipe":
        if not isinstance(payload, Mapping):
            raise VerificationError("recipe 必须是对象")
        try:
            if len(_canonical(dict(payload))) > MAX_RECIPE_BYTES:
                raise VerificationError("recipe 超过大小限制")
        except (TypeError, ValueError) as exc:
            raise VerificationError(f"recipe 无法规范化: {exc}") from exc
        positive = payload.get("positive", payload.get("positive_argv", payload.get("argv")))
        negative = payload.get("negative_control", payload.get("negative", payload.get("negative_argv")))
        if isinstance(positive, Mapping):
            positive_argv = positive.get("argv")
            positive_oracle = _oracle_case(positive.get("oracle", positive), "positive.oracle")
        else:
            positive_argv = positive
            positive_oracle = _oracle_case(
                payload.get("positive_oracle", payload.get("oracle")), "positive_oracle",
            )
        if isinstance(negative, Mapping):
            negative_argv = negative.get("argv")
            negative_oracle = _oracle_case(negative.get("oracle", negative), "negative_control.oracle")
        else:
            negative_argv = negative
            negative_oracle = _oracle_case(payload.get("negative_oracle"), "negative_oracle")
        cwd = _relative_cwd(root, payload.get("cwd", "."))
        timeout = _finite_number(payload.get("timeout_seconds", 30.0), "timeout_seconds", minimum=0.01, maximum=MAX_TIMEOUT_SECONDS)
        reference = _text(payload.get("oracle_reference"), "oracle_reference", max_length=2048)
        oracle_hash = _text(payload.get("oracle_hash"), "oracle_hash", max_length=128)
        if len(oracle_hash) != 64 or any(ch not in "0123456789abcdefABCDEF" for ch in oracle_hash):
            raise VerificationError("oracle_hash 必须是 SHA-256")
        if not _canonical(dict(payload)):
            raise VerificationError("recipe 为空")
        positive_args = tuple(_argv(positive_argv, "positive"))
        negative_args = tuple(_argv(negative_argv, "negative_control"))
        if positive_args == negative_args:
            raise VerificationError("negative_control 必须是独立的固定对照命令")
        return cls(
            positive_argv=positive_args,
            negative_argv=negative_args,
            cwd=cwd,
            positive_oracle=positive_oracle,
            negative_oracle=negative_oracle,
            timeout_seconds=timeout,
            oracle_reference=reference,
            oracle_hash=oracle_hash.lower(),
            input_digest=(None if payload.get("input_digest") is None else _text(payload.get("input_digest"), "input_digest", max_length=128)),
        )

    def digest(self) -> str:
        return _sha256(_canonical({
            "positive_argv": list(self.positive_argv),
            "negative_argv": list(self.negative_argv),
            "cwd": str(self.cwd),
            "positive_oracle": dict(self.positive_oracle),
            "negative_oracle": dict(self.negative_oracle),
            "timeout_seconds": self.timeout_seconds,
            "oracle_reference": self.oracle_reference,
            "oracle_hash": self.oracle_hash,
            "input_digest": self.input_digest,
        }))


def _matches(result: Any, oracle: Mapping[str, object]) -> bool:
    output = getattr(result, "stdout", "") or ""
    output = output.decode("utf-8", errors="replace") if isinstance(output, bytes) else str(output)
    kind = oracle.get("kind")
    if kind == "exit_code":
        return getattr(result, "returncode", None) == oracle.get("expected_exit_code") \
            and not bool(getattr(result, "timed_out", False)) \
            and not bool(getattr(result, "output_exceeded", False))
    if kind == "stdout_contains":
        return bool(oracle.get("text")) and str(oracle["text"]) in output \
            and not bool(getattr(result, "timed_out", False)) \
            and not bool(getattr(result, "output_exceeded", False))
    if kind == "json":
        if bool(getattr(result, "timed_out", False)) or bool(getattr(result, "output_exceeded", False)):
            return False
        try:
            value: Any = json.loads(output)
        except (TypeError, ValueError, json.JSONDecodeError):
            return False
        for part in str(oracle.get("path", "")).split("."):
            if not isinstance(value, Mapping) or part not in value:
                return False
            value = value[part]
        return value == oracle.get("equals")
    return False


def _result_record(result: Any, *, execution_id: str, case: str, argv: Sequence[str], oracle: Mapping[str, object]) -> dict[str, object]:
    stdout_value = getattr(result, "stdout", "") or ""
    stderr_value = getattr(result, "stderr", "") or ""
    stdout = stdout_value if isinstance(stdout_value, bytes) else str(stdout_value).encode("utf-8", errors="replace")
    stderr = stderr_value if isinstance(stderr_value, bytes) else str(stderr_value).encode("utf-8", errors="replace")
    return {
        "execution_id": execution_id,
        "case": case,
        "argv": list(argv),
        "exit_code": getattr(result, "returncode", None),
        "pid": getattr(result, "pid", None),
        "timed_out": bool(getattr(result, "timed_out", False)),
        "output_exceeded": bool(getattr(result, "output_exceeded", False)),
        "duration_seconds": float(getattr(result, "duration_seconds", 0.0) or 0.0),
        "stdout": stdout.decode("utf-8", errors="replace"),
        "stderr": stderr.decode("utf-8", errors="replace"),
        "stdout_sha256": _sha256(stdout),
        "stderr_sha256": _sha256(stderr),
        "oracle": dict(oracle),
        "oracle_matched": _matches(result, oracle),
    }


def _atomic_json(path: Path, payload: Mapping[str, object]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    raw = _canonical(payload)
    descriptor, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=str(path.parent))
    try:
        os.fchmod(descriptor, 0o600)
        with os.fdopen(descriptor, "wb") as handle:
            handle.write(raw)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, path)
    except BaseException:
        try:
            os.close(descriptor)
        except OSError:
            pass
        try:
            os.unlink(temporary)
        except OSError:
            pass
        raise


def verify_finding(root: Path, finding: Mapping[str, object], recipe: Mapping[str, object] | VerificationRecipe,
                   *, run_id: str | None = None, lifecycle_id: str | None = None,
                   round_no: int | None = None, target_fingerprint: str | None = None,
                   state_revision: int | None = None, request_id: str | None = None,
                   artifact_root: Path | None = None, runner: Any = run_bounded) -> dict[str, object]:
    """Run the engine-owned positive/control matrix and persist its receipt."""
    root = Path(root).resolve()
    if not root.is_dir():
        raise VerificationError("项目根目录不存在")
    if isinstance(recipe, VerificationRecipe):
        spec = recipe
    else:
        spec = VerificationRecipe.from_mapping(root, recipe)
    if request_id is not None:
        _text(request_id, "request_id", max_length=128)
    finding_key = finding.get("fingerprint") or finding.get("id") or finding.get("finding_id")
    finding_key = _text(finding_key, "finding_key", max_length=512)
    try:
        finding_content = _canonical(dict(finding))
    except (TypeError, ValueError) as exc:
        raise VerificationError(f"finding 无法规范化: {exc}") from exc
    if len(finding_content) > MAX_RECIPE_BYTES:
        raise VerificationError("finding 内容超过大小限制")
    finding_content_hash = _sha256(finding_content)
    base = Path(artifact_root) if artifact_root is not None else root / ".bugx" / "verification"
    base = base.resolve()
    try:
        base.relative_to(root)
    except ValueError as exc:
        raise VerificationError("artifact_root 越界") from exc
    verification_id = str(uuid.uuid4())
    directory = base / verification_id
    directory.mkdir(parents=True, exist_ok=False, mode=0o700)
    records: list[dict[str, object]] = []
    try:
        for index in range(POSITIVE_RUNS_REQUIRED):
            execution_id = f"{verification_id}-positive-{index + 1}"
            result = runner(
                list(spec.positive_argv), cwd=spec.cwd, timeout=spec.timeout_seconds,
                max_total_timeout=spec.timeout_seconds, max_output_bytes=MAX_OUTPUT_BYTES,
            )
            record = _result_record(result, execution_id=execution_id, case="positive", argv=spec.positive_argv, oracle=spec.positive_oracle)
            record["run_index"] = index + 1
            records.append(record)
        control_id = f"{verification_id}-negative-control"
        result = runner(
            list(spec.negative_argv), cwd=spec.cwd, timeout=spec.timeout_seconds,
            max_total_timeout=spec.timeout_seconds, max_output_bytes=MAX_OUTPUT_BYTES,
        )
        control = _result_record(result, execution_id=control_id, case="negative_control", argv=spec.negative_argv, oracle=spec.negative_oracle)
        records.append(control)
    except (OSError, TypeError, WorkerExecutionError, VerificationError) as exc:
        receipt = {
            "protocol_version": PROTOCOL_VERSION, "status": "BLOCKED",
            "verification_id": verification_id, "finding_key": finding_key,
            "request_id": request_id,
            "error": str(exc)[:512], "recipe_digest": spec.digest(),
        }
        _atomic_json(directory / "receipt.json", receipt)
        return receipt
    positives_ok = len(records) == 3 and all(bool(item.get("oracle_matched")) for item in records[:2])
    negative_ok = bool(records[2].get("oracle_matched"))
    status = "CONFIRMED" if positives_ok and negative_ok else "CANDIDATE"
    receipt: dict[str, object] = {
        "protocol_version": PROTOCOL_VERSION,
        "status": status,
        "verification_id": verification_id,
        "request_id": request_id,
        "finding_key": finding_key,
        "finding_content_sha256": finding_content_hash,
        "run_id": run_id,
        "lifecycle_id": lifecycle_id,
        "round_no": round_no,
        "state_revision": state_revision,
        "target_fingerprint": target_fingerprint,
        "recipe_digest": spec.digest(),
        "oracle_reference": spec.oracle_reference,
        "oracle_hash": spec.oracle_hash,
        "positive_runs": records[:2],
        "negative_control": records[2],
        "raw_output_source": "engine",
        "receipt_path": str(directory / "receipt.json"),
        "created_at": time.time(),
    }
    receipt["verification_digest"] = _sha256(_canonical(receipt))
    _atomic_json(directory / "receipt.json", receipt)
    return receipt


def verify_finding_record(*args: Any, **kwargs: Any) -> dict[str, object]:
    """Compatibility alias for callers that prefer an explicit record name."""
    return verify_finding(*args, **kwargs)


