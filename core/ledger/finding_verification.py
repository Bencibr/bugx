import time
import uuid
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Mapping, Sequence

import core.secure_atomic as secure_atomic
from core.supervisor.worker_execution import run_bounded, WorkerExecutionError


PROTOCOL_VERSION = 2
MAX_RECIPE_BYTES = 128 * 1024
MAX_OUTPUT_BYTES = 2 * 1024 * 1024
MAX_TIMEOUT_SECONDS = 900.0
POSITIVE_RUNS_REQUIRED = 2


class VerificationError(ValueError):
    """Recipe, binding or execution record failed closed validation."""


class VerificationBlocked(VerificationError):
    """The requested execution cannot be provided safely on this platform."""


def _canonical(value: object) -> bytes:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"), allow_nan=False).encode("utf-8")


def _sha256(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def _text(value: object, field: str, *, max_length: int = 4096) -> str:
    if not isinstance(value, str) or not value.strip() or len(value) > max_length:
        raise VerificationError(f"{field} 必须是非空字符串")
    return value.strip()


def _argv(value: object, field: str) -> list[str]:
    if isinstance(value, (str, bytes)) or not isinstance(value, Sequence):
        raise VerificationError(f"{field} 必须是 argv 数组，禁止 shell 字符串")
    result = list(value)
    if not result or len(result) > 256 or any(not isinstance(item, str) or not item for item in result):
        raise VerificationError(f"{field} 必须是非空字符串数组")
    if any(any(token in item for token in (";", "&&", "||", "`", "$(", ">", "<")) for item in result):
        raise VerificationError(f"{field} 不能包含 shell 运算符")
    return result


def _finite_number(value: object, field: str, *, minimum: float = 0.0, maximum: float | None = None) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise VerificationError(f"{field} 必须是数字")
    value = float(value)
    if not math.isfinite(value) or value < minimum or (maximum is not None and value > maximum):
        raise VerificationError(f"{field} 超出范围")
    return value


def _relative_cwd(root: Path, value: object) -> Path:
    raw = _text(value, "cwd", max_length=1024)
    candidate = Path(raw)
    if candidate.is_absolute():
        raise VerificationError("recipe.cwd 必须是相对项目根路径")
    resolved_root = root.resolve()
    lexical = resolved_root / candidate
    # Reject a symlinked cwd before resolving it; resolving first would erase
    # the evidence and turn an escape into an apparently confined directory.
    cursor = resolved_root
    for part in candidate.parts:
        if part in {"", "."}:
            continue
        cursor = cursor / part
        if cursor.is_symlink():
            raise VerificationError("recipe.cwd 不能穿过符号链接")
    resolved = lexical.resolve()
    try:
        resolved.relative_to(resolved_root)
    except ValueError as exc:
        raise VerificationError("recipe.cwd 越界") from exc
    if not resolved.is_dir() or resolved.is_symlink():
        raise VerificationError("recipe.cwd 不是安全目录")
    return resolved


def _oracle_case(value: object, field: str) -> dict[str, object]:
    if not isinstance(value, Mapping):
        raise VerificationError(f"{field} 必须是对象")
    kind = _text(value.get("kind", value.get("type", "exit_code")), f"{field}.kind", max_length=64)
    if kind not in {"exit_code", "stdout_contains", "json"}:
        raise VerificationError(f"{field}.kind 不支持: {kind}")
    normalized = dict(value)
    normalized["kind"] = kind
    if kind == "exit_code":
        expected = value.get("expected_exit_code", value.get("exit_code"))
        if isinstance(expected, bool) or not isinstance(expected, int) or expected < -255 or expected > 255:
            raise VerificationError(f"{field}.expected_exit_code 无效")
        normalized["expected_exit_code"] = expected
    elif kind == "stdout_contains":
        normalized["text"] = _text(value.get("text"), f"{field}.text", max_length=1024)
    else:
        normalized["path"] = _text(value.get("path"), f"{field}.path", max_length=256)
        if "equals" not in value:
            # F-RSI-20261115-122：equals 漏配会被 _matches 的 value == None
            # 误判为命中（JSON 路径值恰为 null 时 None == None），漏配与
            # 「期望 null」不可区分——构造期 fail-fast；显式传 null 保留
            # （期望 null 值是合法判据语义）。
            raise VerificationError(f"{field}.equals 缺失（期望 null 请显式传 null）")
        normalized["equals"] = value.get("equals")
    return normalized


@dataclass(frozen=True)
class VerificationRecipe:
    """Validated immutable recipe used for all positive/control executions."""

    positive_argv: tuple[str, ...]
    negative_argv: tuple[str, ...]
    cwd: Path
    positive_oracle: Mapping[str, object]
    negative_oracle: Mapping[str, object]
    timeout_seconds: float
    oracle_reference: str
    oracle_hash: str
    input_digest: str | None = None

    @classmethod
    def from_mapping(cls, root: Path, payload: Mapping[str, object]) -> "VerificationRecipe":
        if not isinstance(payload, Mapping):
            raise VerificationError("recipe 必须是对象")
        try:
            if len(_canonical(dict(payload))) > MAX_RECIPE_BYTES:
                raise VerificationError("recipe 超过大小限制")
        except (TypeError, ValueError) as exc:
            raise VerificationError(f"recipe 无法规范化: {exc}") from exc
        positive = payload.get("positive", payload.get("positive_argv", payload.get("argv")))
        negative = payload.get("negative_control", payload.get("negative", payload.get("negative_argv")))
        if isinstance(positive, Mapping):
            positive_argv = positive.get("argv")
            positive_oracle = _oracle_case(positive.get("oracle", positive), "positive.oracle")
        else:
            positive_argv = positive
            positive_oracle = _oracle_case(
                payload.get("positive_oracle", payload.get("oracle")), "positive_oracle",
            )
        if isinstance(negative, Mapping):
            negative_argv = negative.get("argv")
            negative_oracle = _oracle_case(negative.get("oracle", negative), "negative_control.oracle")
        else:
            negative_argv = negative
            negative_oracle = _oracle_case(payload.get("negative_oracle"), "negative_oracle")
        cwd = _relative_cwd(root, payload.get("cwd", "."))
        timeout = _finite_number(payload.get("timeout_seconds", 30.0), "timeout_seconds", minimum=0.01, maximum=MAX_TIMEOUT_SECONDS)
        reference = _text(payload.get("oracle_reference"), "oracle_reference", max_length=2048)
        oracle_hash = _text(payload.get("oracle_hash"), "oracle_hash", max_length=128)
        if len(oracle_hash) != 64 or any(ch not in "0123456789abcdefABCDEF" for ch in oracle_hash):
            raise VerificationError("oracle_hash 必须是 SHA-256")
        if not _canonical(dict(payload)):
            raise VerificationError("recipe 为空")
        positive_args = tuple(_argv(positive_argv, "positive"))
        negative_args = tuple(_argv(negative_argv, "negative_control"))
        if positive_args == negative_args:
            raise VerificationError("negative_control 必须是独立的固定对照命令")
        return cls(
            positive_argv=positive_args,
            negative_argv=negative_args,
            cwd=cwd,
            positive_oracle=positive_oracle,
            negative_oracle=negative_oracle,
            timeout_seconds=timeout,
            oracle_reference=reference,
            oracle_hash=oracle_hash.lower(),
            input_digest=(None if payload.get("input_digest") is None else _text(payload.get("input_digest"), "input_digest", max_length=128)),
        )

    def digest(self) -> str:
        return _sha256(_canonical({
            "positive_argv": list(self.positive_argv),
            "negative_argv": list(self.negative_argv),
            "cwd": str(self.cwd),
            "positive_oracle": dict(self.positive_oracle),
            "negative_oracle": dict(self.negative_oracle),
            "timeout_seconds": self.timeout_seconds,
            "oracle_reference": self.oracle_reference,
            "oracle_hash": self.oracle_hash,
            "input_digest": self.input_digest,
        }))


def _matches(result: Any, oracle: Mapping[str, object]) -> bool:
    output = getattr(result, "stdout", "") or ""
    output = output.decode("utf-8", errors="replace") if isinstance(output, bytes) else str(output)
    kind = oracle.get("kind")
    if kind == "exit_code":
        return getattr(result, "returncode", None) == oracle.get("expected_exit_code") \
            and not bool(getattr(result, "timed_out", False)) \
            and not bool(getattr(result, "output_exceeded", False))
    if kind == "stdout_contains":
        return bool(oracle.get("text")) and str(oracle["text"]) in output \
            and not bool(getattr(result, "timed_out", False)) \
            and not bool(getattr(result, "output_exceeded", False))
    if kind == "json":
        if bool(getattr(result, "timed_out", False)) or bool(getattr(result, "output_exceeded", False)):
            return False
        try:
            value: Any = json.loads(output)
        except (TypeError, ValueError, json.JSONDecodeError):
            return False
        for part in str(oracle.get("path", "")).split("."):
            if not isinstance(value, Mapping) or part not in value:
                return False
            value = value[part]
        return value == oracle.get("equals")
    return False


def _result_record(result: Any, *, execution_id: str, case: str, argv: Sequence[str], oracle: Mapping[str, object]) -> dict[str, object]:
    stdout_value = getattr(result, "stdout", "") or ""
    stderr_value = getattr(result, "stderr", "") or ""
    stdout = stdout_value if isinstance(stdout_value, bytes) else str(stdout_value).encode("utf-8", errors="replace")
    stderr = stderr_value if isinstance(stderr_value, bytes) else str(stderr_value).encode("utf-8", errors="replace")
    return {
        "execution_id": execution_id,
        "case": case,
        "argv": list(argv),
        "exit_code": getattr(result, "returncode", None),
        "pid": getattr(result, "pid", None),
        "timed_out": bool(getattr(result, "timed_out", False)),
        "output_exceeded": bool(getattr(result, "output_exceeded", False)),
        "duration_seconds": float(getattr(result, "duration_seconds", 0.0) or 0.0),
        "stdout": stdout.decode("utf-8", errors="replace"),
        "stderr": stderr.decode("utf-8", errors="replace"),
        "stdout_sha256": _sha256(stdout),
        "stderr_sha256": _sha256(stderr),
        "oracle": dict(oracle),
        "oracle_matched": _matches(result, oracle),
    }


def _atomic_json(path: Path, payload: Mapping[str, object]) -> None:
    secure_atomic.atomic_write_bytes(path, _canonical(payload), mode=0o600, parent_mode=0o700)


def verify_finding(root: Path, finding: Mapping[str, object], recipe: Mapping[str, object] | VerificationRecipe,
                   *, run_id: str | None = None, lifecycle_id: str | None = None,
                   round_no: int | None = None, target_fingerprint: str | None = None,
                   state_revision: int | None = None, request_id: str | None = None,
                   artifact_root: Path | None = None, runner: Any = run_bounded) -> dict[str, object]:
    """Run the engine-owned positive/control matrix and persist its receipt."""
    root = Path(root).resolve()
    if not root.is_dir():
        raise VerificationError("项目根目录不存在")
    if isinstance(recipe, VerificationRecipe):
        spec = recipe
    else:
        spec = VerificationRecipe.from_mapping(root, recipe)
    if request_id is not None:
        _text(request_id, "request_id", max_length=128)
    finding_key = finding.get("fingerprint") or finding.get("id") or finding.get("finding_id")
    finding_key = _text(finding_key, "finding_key", max_length=512)
    try:
        finding_content = _canonical(dict(finding))
    except (TypeError, ValueError) as exc:
        raise VerificationError(f"finding 无法规范化: {exc}") from exc
    if len(finding_content) > MAX_RECIPE_BYTES:
        raise VerificationError("finding 内容超过大小限制")
    finding_content_hash = _sha256(finding_content)
    base = Path(artifact_root) if artifact_root is not None else root / ".bugx" / "verification"
    base = base.resolve()
    try:
        base.relative_to(root)
    except ValueError as exc:
        raise VerificationError("artifact_root 越界") from exc
    verification_id = str(uuid.uuid4())
    directory = base / verification_id
    records: list[dict[str, object]] = []
    # F-RSI-20261110-021：artifact_root 不可写（只读挂载/磁盘满/权限收紧）时
    # 目录创建与 BLOCKED receipt 落盘都会 OSError——此前裸异常冒出 verify_finding，
    # 上游只能靠 dispatch 兜底丢结构化语义。降级为内存 BLOCKED receipt：
    # receipt_path 置 None + degraded 标记，双跑照常执行（结果不落盘但可审计）。
    degraded_storage = False
    try:
        directory.mkdir(parents=True, exist_ok=False, mode=0o700)
    except OSError as exc:
        degraded_storage = True
        directory = None
        storage_error = f"artifact_root 不可写（{type(exc).__name__}: {exc}）"
    records: list[dict[str, object]] = []
    try:
        for index in range(POSITIVE_RUNS_REQUIRED):
            execution_id = f"{verification_id}-positive-{index + 1}"
            result = runner(
                list(spec.positive_argv), cwd=spec.cwd, timeout=spec.timeout_seconds,
                max_total_timeout=spec.timeout_seconds, max_output_bytes=MAX_OUTPUT_BYTES,
            )
            record = _result_record(result, execution_id=execution_id, case="positive", argv=spec.positive_argv, oracle=spec.positive_oracle)
            record["run_index"] = index + 1
            records.append(record)
        control_id = f"{verification_id}-negative-control"
        result = runner(
            list(spec.negative_argv), cwd=spec.cwd, timeout=spec.timeout_seconds,
            max_total_timeout=spec.timeout_seconds, max_output_bytes=MAX_OUTPUT_BYTES,
        )
        control = _result_record(result, execution_id=control_id, case="negative_control", argv=spec.negative_argv, oracle=spec.negative_oracle)
        records.append(control)
    except (OSError, TypeError, WorkerExecutionError, VerificationError) as exc:
        receipt = {
            "protocol_version": PROTOCOL_VERSION, "status": "BLOCKED",
            "verification_id": verification_id, "finding_key": finding_key,
            "request_id": request_id,
            "error": str(exc)[:512], "recipe_digest": spec.digest(),
        }
        if directory is not None:
            try:
                _atomic_json(directory / "receipt.json", receipt)
                receipt["receipt_path"] = str(directory / "receipt.json")
            except OSError:
                pass  # 落盘失败也返回内存 BLOCKED receipt（F-021 degraded）
        else:
            receipt["degraded"] = True
        return receipt
    positives_ok = (
        len(records) == POSITIVE_RUNS_REQUIRED + 1
        and all(bool(item.get("oracle_matched")) for item in records[:POSITIVE_RUNS_REQUIRED])
    )
    negative_ok = bool(records[POSITIVE_RUNS_REQUIRED].get("oracle_matched"))
    status = "CONFIRMED" if positives_ok and negative_ok else "CANDIDATE"
    receipt: dict[str, object] = {
        "protocol_version": PROTOCOL_VERSION,
        "status": status,
        "verification_id": verification_id,
        "request_id": request_id,
        "finding_key": finding_key,
        "finding_content_sha256": finding_content_hash,
        "run_id": run_id,
        "lifecycle_id": lifecycle_id,
        "round_no": round_no,
        "state_revision": state_revision,
        "target_fingerprint": target_fingerprint,
        "recipe_digest": spec.digest(),
        "oracle_reference": spec.oracle_reference,
        "oracle_hash": spec.oracle_hash,
        "positive_runs": records[:POSITIVE_RUNS_REQUIRED],
        "negative_control": records[POSITIVE_RUNS_REQUIRED],
        "raw_output_source": "engine",
        "receipt_path": str(directory / "receipt.json") if directory is not None else None,
        "created_at": time.time(),
    }
    receipt["verification_digest"] = _sha256(_canonical(receipt))
    if directory is not None:
        try:
            _atomic_json(directory / "receipt.json", receipt)
            receipt["receipt_path"] = str(directory / "receipt.json")
        except OSError:
            receipt["degraded"] = True
            receipt["receipt_path"] = None
    else:
        receipt["degraded"] = True
        receipt["receipt_path"] = None
    return receipt


def verify_finding_record(*args: Any, **kwargs: Any) -> dict[str, object]:
    """Compatibility alias for callers that prefer an explicit record name."""
    return verify_finding(*args, **kwargs)


DIAGNOSTIC_MAX_TEXT_BYTES = 4096

FAILURE_CODES = frozenset({
    "shell_token_rejected",
    "syntax_or_import_error",
    "positive_not_triggered",
    "positive_flaky",
    "negative_false_trigger",
    "negative_trivial_rejected",
    "env_or_dependency_blocked",
    "timeout_exceeded",
    "source_tampered_rejected",
    "verifier_stalled",
})

RETRYABLE_FAILURE_CODES = frozenset({
    "shell_token_rejected",
    "syntax_or_import_error",
    "positive_not_triggered",
    "negative_false_trigger",
    "negative_trivial_rejected",
})

_REDACT_PATTERNS: tuple[tuple[re.Pattern[str], str], ...] = (
    (re.compile(r"(?i)(bearer\s+)[A-Za-z0-9._\-]{12,}"), r"\1<REDACTED>"),
    (re.compile(r"\b(?:sk|pk|ghp|gho|ghu|ghs|glpat|xoxb|xoxp)-[A-Za-z0-9_\-]{10,}\b"), "<REDACTED_TOKEN>"),
    (re.compile(r"(?i)(\b(?:api[_-]?key|secret|token|password|passwd|access[_-]?key)\s*[:=]\s*['\"]?)([^\s'\",;]{6,})"), r"\1<REDACTED>"),
)

_TRIVIAL_BUILTINS = frozenset({
    "print", "len", "str", "int", "float", "bool", "list", "dict", "set", "tuple",
    "range", "repr", "type", "isinstance", "issubclass", "enumerate", "zip",
    "min", "max", "sum", "abs", "round", "sorted", "reversed", "any", "all",
    "chr", "ord", "id", "hash", "exit", "quit",
})


def _redact_and_truncate(text: object, *, limit: int = DIAGNOSTIC_MAX_TEXT_BYTES) -> str:
    raw = text.decode("utf-8", errors="replace") if isinstance(text, bytes) else str(text or "")
    for pattern, repl in _REDACT_PATTERNS:
        raw = pattern.sub(repl, raw)
    encoded = raw.encode("utf-8", errors="replace")
    if len(encoded) <= limit:
        return raw
    truncated = encoded[:limit].decode("utf-8", errors="ignore")
    return f"{truncated}\n...[truncated {len(encoded) - limit} bytes]"


def _looks_like_syntax_or_import(stderr: str, stdout: str) -> bool:
    combined = f"{stderr}\n{stdout}"
    markers = (
        "SyntaxError",
        "IndentationError",
        "TabError",
        "ImportError",
        "ModuleNotFoundError",
        "NameError",
        "AttributeError: module",
        "BUGX_VERIFY_POSITIVE unexpected-error=SyntaxError",
        "BUGX_VERIFY_POSITIVE unexpected-error=ImportError",
        "BUGX_VERIFY_POSITIVE unexpected-error=ModuleNotFoundError",
        "BUGX_VERIFY_POSITIVE unexpected-error=NameError",
    )
    return any(marker in combined for marker in markers)


def _looks_like_env_blocked(stderr: str, stdout: str, error_text: str = "") -> bool:
    combined = f"{error_text}\n{stderr}\n{stdout}".lower()
    markers = (
        "connection refused",
        "no such file or directory: 'docker'",
        "permission denied",
        "operation not permitted",
        "cannot connect to",
        "address already in use",
        "executable file not found",
        "command not found",
    )
    return any(marker in combined for marker in markers)


@dataclass(frozen=True)
class VerificationDiagnostic:
    """Engine-owned structured diagnostic for a failed verification attempt."""

    finding_key: str
    attempt: int
    failure_code: str
    stage: str
    retryable: bool
    summary: str
    exit_code: int | None = None
    stdout_excerpt: str = ""
    stderr_excerpt: str = ""
    receipt_status: str = ""
    verification_id: str | None = None
    created_at: float = 0.0

    def to_dict(self) -> dict[str, object]:
        return {
            "finding_key": self.finding_key,
            "attempt": self.attempt,
            "failure_code": self.failure_code,
            "stage": self.stage,
            "retryable": self.retryable,
            "summary": self.summary,
            "exit_code": self.exit_code,
            "stdout_excerpt": self.stdout_excerpt,
            "stderr_excerpt": self.stderr_excerpt,
            "receipt_status": self.receipt_status,
            "verification_id": self.verification_id,
            "created_at": self.created_at or time.time(),
        }


def diagnose_verification_error(
    exc_or_msg: object,
    *,
    attempt: int = 1,
    finding_key: str = "",
    failure_code: str | None = None,
    stage: str = "precheck",
) -> VerificationDiagnostic:
    """Build a structured diagnostic from a precheck/supervisor/runtime error."""
    text = _redact_and_truncate(str(exc_or_msg))
    code = failure_code
    if code not in FAILURE_CODES:
        lowered = text.lower()
        if "shell" in lowered or "禁字符" in text or "运算符" in text:
            code = "shell_token_rejected"
        elif "timeout" in lowered or "超时" in text:
            code = "timeout_exceeded"
        elif _looks_like_env_blocked(text, "", text):
            code = "env_or_dependency_blocked"
        elif _looks_like_syntax_or_import(text, ""):
            code = "syntax_or_import_error"
        else:
            code = "positive_not_triggered"
    return VerificationDiagnostic(
        finding_key=finding_key,
        attempt=attempt,
        failure_code=code,
        stage=stage,
        retryable=code in RETRYABLE_FAILURE_CODES,
        summary=text[:400],
        stderr_excerpt=text,
        receipt_status="ERROR",
        created_at=time.time(),
    )


def diagnose_verification_receipt(
    receipt: Mapping[str, object],
    *,
    attempt: int = 1,
    finding_key: str = "",
) -> VerificationDiagnostic:
    """Classify an engine verification receipt into a deterministic failure_code."""
    fkey = finding_key or str(receipt.get("finding_key") or "")
    status = str(receipt.get("status") or "")
    vid = receipt.get("verification_id")
    vid_str = str(vid) if vid is not None else None
    now = time.time()

    if status == "BLOCKED":
        err = _redact_and_truncate(receipt.get("error") or "verification blocked")
        code = "timeout_exceeded" if "timeout" in err.lower() else "env_or_dependency_blocked"
        return VerificationDiagnostic(
            finding_key=fkey,
            attempt=attempt,
            failure_code=code,
            stage="blocked",
            retryable=False,
            summary=err[:400],
            stderr_excerpt=err,
            receipt_status=status,
            verification_id=vid_str,
            created_at=now,
        )

    pos_runs = receipt.get("positive_runs")
    pos_list = list(pos_runs) if isinstance(pos_runs, Sequence) else []
    neg = receipt.get("negative_control")
    neg_map = neg if isinstance(neg, Mapping) else {}

    # 1. Timeout check across all runs
    for idx, run in enumerate(pos_list, 1):
        if isinstance(run, Mapping) and bool(run.get("timed_out")):
            return VerificationDiagnostic(
                finding_key=fkey,
                attempt=attempt,
                failure_code="timeout_exceeded",
                stage=f"positive_run_{idx}",
                retryable=False,
                summary=f"positive run {idx} timed out",
                exit_code=run.get("exit_code") if isinstance(run.get("exit_code"), int) else None,
                stdout_excerpt=_redact_and_truncate(run.get("stdout")),
                stderr_excerpt=_redact_and_truncate(run.get("stderr")),
                receipt_status=status,
                verification_id=vid_str,
                created_at=now,
            )
    if bool(neg_map.get("timed_out")):
        return VerificationDiagnostic(
            finding_key=fkey,
            attempt=attempt,
            failure_code="timeout_exceeded",
            stage="negative_control",
            retryable=False,
            summary="negative control timed out",
            exit_code=neg_map.get("exit_code") if isinstance(neg_map.get("exit_code"), int) else None,
            stdout_excerpt=_redact_and_truncate(neg_map.get("stdout")),
            stderr_excerpt=_redact_and_truncate(neg_map.get("stderr")),
            receipt_status=status,
            verification_id=vid_str,
            created_at=now,
        )

    # 2. Positive runs analysis
    pos_matched = [bool(r.get("oracle_matched")) for r in pos_list if isinstance(r, Mapping)]
    if len(pos_matched) >= 2 and any(pos_matched) and not all(pos_matched):
        failed_idx = next(i for i, ok in enumerate(pos_matched) if not ok)
        run = pos_list[failed_idx]
        return VerificationDiagnostic(
            finding_key=fkey,
            attempt=attempt,
            failure_code="positive_flaky",
            stage=f"positive_run_{failed_idx + 1}",
            retryable=False,
            summary="positive runs disagreed across independent executions (non-deterministic)",
            exit_code=run.get("exit_code") if isinstance(run.get("exit_code"), int) else None,
            stdout_excerpt=_redact_and_truncate(run.get("stdout")),
            stderr_excerpt=_redact_and_truncate(run.get("stderr")),
            receipt_status=status,
            verification_id=vid_str,
            created_at=now,
        )

    if not pos_matched or not all(pos_matched):
        run = pos_list[0] if pos_list and isinstance(pos_list[0], Mapping) else {}
        stdout = _redact_and_truncate(run.get("stdout"))
        stderr = _redact_and_truncate(run.get("stderr"))
        if _looks_like_syntax_or_import(stderr, stdout):
            code = "syntax_or_import_error"
            summary = "positive PoC failed with syntax/import/name error"
        elif _looks_like_env_blocked(stderr, stdout):
            code = "env_or_dependency_blocked"
            summary = "positive PoC blocked by missing environment or permission"
        else:
            code = "positive_not_triggered"
            summary = f"positive PoC did not match oracle (exit_code={run.get('exit_code')})"
        return VerificationDiagnostic(
            finding_key=fkey,
            attempt=attempt,
            failure_code=code,
            stage="positive_run_1",
            retryable=code in RETRYABLE_FAILURE_CODES,
            summary=summary,
            exit_code=run.get("exit_code") if isinstance(run.get("exit_code"), int) else None,
            stdout_excerpt=stdout,
            stderr_excerpt=stderr,
            receipt_status=status,
            verification_id=vid_str,
            created_at=now,
        )

    # 3. Negative control analysis
    if not bool(neg_map.get("oracle_matched")):
        stdout = _redact_and_truncate(neg_map.get("stdout"))
        stderr = _redact_and_truncate(neg_map.get("stderr"))
        if _looks_like_syntax_or_import(stderr, stdout):
            code = "syntax_or_import_error"
            summary = "negative control failed with syntax/import/name error"
        elif _looks_like_env_blocked(stderr, stdout):
            code = "env_or_dependency_blocked"
            summary = "negative control blocked by missing environment or permission"
        else:
            code = "negative_false_trigger"
            summary = f"negative control unexpectedly failed oracle (exit_code={neg_map.get('exit_code')})"
        return VerificationDiagnostic(
            finding_key=fkey,
            attempt=attempt,
            failure_code=code,
            stage="negative_control",
            retryable=code in RETRYABLE_FAILURE_CODES,
            summary=summary,
            exit_code=neg_map.get("exit_code") if isinstance(neg_map.get("exit_code"), int) else None,
            stdout_excerpt=stdout,
            stderr_excerpt=stderr,
            receipt_status=status,
            verification_id=vid_str,
            created_at=now,
        )

    return VerificationDiagnostic(
        finding_key=fkey,
        attempt=attempt,
        failure_code="positive_not_triggered",
        stage="unknown",
        retryable=True,
        summary=f"verification receipt did not reach CONFIRMED (status={status})",
        receipt_status=status,
        verification_id=vid_str,
        created_at=now,
    )


def _has_meaningful_target_activity(tree: ast.AST, target_hints: Sequence[str]) -> bool:
    """Reject trivial no-op negative controls (e.g. `pass`, `sys.exit(0)`, `print('ok')`)."""
    has_import = False
    non_trivial_call = False
    imported_names: set[str] = set()
    referenced_names: set[str] = set()

    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                root_name = alias.name.split(".")[0]
                if root_name != "sys":
                    has_import = True
                imported_names.add(alias.name)
                imported_names.add(root_name)
                if alias.asname:
                    imported_names.add(alias.asname)
        elif isinstance(node, ast.ImportFrom):
            mod = node.module or ""
            if mod and mod.split(".")[0] != "sys":
                has_import = True
            if mod:
                imported_names.add(mod)
                imported_names.add(mod.split(".")[0])
            for alias in node.names:
                imported_names.add(alias.name)
                if alias.asname:
                    imported_names.add(alias.asname)
        elif isinstance(node, ast.Name):
            referenced_names.add(node.id)
        elif isinstance(node, ast.Attribute):
            referenced_names.add(node.attr)
        elif isinstance(node, ast.Call):
            func = node.func
            if isinstance(func, ast.Name):
                if func.id not in _TRIVIAL_BUILTINS:
                    non_trivial_call = True
            elif isinstance(func, ast.Attribute):
                is_sys_exit = (
                    isinstance(func.value, ast.Name)
                    and func.value.id == "sys"
                    and func.attr == "exit"
                )
                if not is_sys_exit:
                    non_trivial_call = True
            else:
                non_trivial_call = True

    if not (non_trivial_call or has_import):
        return False
    if not non_trivial_call:
        return False
    if target_hints:
        all_tokens = imported_names | referenced_names
        normalized_hints = {h.strip() for h in target_hints if isinstance(h, str) and h.strip()}
        if normalized_hints and not any(
            hint in token or token in hint
            for hint in normalized_hints
            for token in all_tokens
            if len(token) >= 2
        ):
            return False
    return True


def validate_python_poc_pair(
    positive_code: str,
    negative_code: str,
    *,
    finding_key: str = "",
    attempt: int = 1,
    target_hints: Sequence[str] = (),
) -> VerificationDiagnostic | None:
    """Anti-gaming static AST validation for positive/negative Python PoC bodies."""
    pos_text = (positive_code or "").strip()
    neg_text = (negative_code or "").strip()
    if not pos_text or not neg_text:
        return VerificationDiagnostic(
            finding_key=finding_key,
            attempt=attempt,
            failure_code="syntax_or_import_error",
            stage="ast_precheck",
            retryable=True,
            summary="positive and negative code bodies must both be non-empty",
            created_at=time.time(),
        )
    if pos_text == neg_text:
        return VerificationDiagnostic(
            finding_key=finding_key,
            attempt=attempt,
            failure_code="negative_trivial_rejected",
            stage="ast_precheck",
            retryable=True,
            summary="negative control must differ from positive payload",
            created_at=time.time(),
        )
    try:
        pos_tree = ast.parse(pos_text, filename="verification-positive")
    except SyntaxError as exc:
        return VerificationDiagnostic(
            finding_key=finding_key,
            attempt=attempt,
            failure_code="syntax_or_import_error",
            stage="ast_precheck",
            retryable=True,
            summary=f"positive SyntaxError: {exc}",
            stderr_excerpt=str(exc),
            created_at=time.time(),
        )
    try:
        neg_tree = ast.parse(neg_text, filename="verification-negative")
    except SyntaxError as exc:
        return VerificationDiagnostic(
            finding_key=finding_key,
            attempt=attempt,
            failure_code="syntax_or_import_error",
            stage="ast_precheck",
            retryable=True,
            summary=f"negative SyntaxError: {exc}",
            stderr_excerpt=str(exc),
            created_at=time.time(),
        )
    if not _has_meaningful_target_activity(neg_tree, target_hints):
        return VerificationDiagnostic(
            finding_key=finding_key,
            attempt=attempt,
            failure_code="negative_trivial_rejected",
            stage="ast_precheck",
            retryable=True,
            summary="negative control rejected as trivial no-op (must invoke target module/entry)",
            created_at=time.time(),
        )
    if not _has_meaningful_target_activity(pos_tree, ()):
        return VerificationDiagnostic(
            finding_key=finding_key,
            attempt=attempt,
            failure_code="positive_not_triggered",
            stage="ast_precheck",
            retryable=True,
            summary="positive PoC contains no meaningful call or module exercise",
            created_at=time.time(),
        )
    return None


def snapshot_target_hashes(root: Path, rel_paths: Sequence[str]) -> dict[str, str]:
    """Compute SHA-256 hashes of target source files before PoC execution."""
    resolved_root = Path(root).resolve()
    hashes: dict[str, str] = {}
    for raw in rel_paths:
        if not isinstance(raw, str) or not raw.strip():
            continue
        candidate = Path(raw.replace("\\", "/"))
        if candidate.is_absolute() or ".." in candidate.parts:
            continue
        try:
            target = (resolved_root / candidate).resolve()
            target.relative_to(resolved_root)
        except (OSError, ValueError):
            continue
        if target.is_file() and not target.is_symlink():
            try:
                hashes[str(target.relative_to(resolved_root))] = _sha256(target.read_bytes())
            except OSError:
                continue
    return hashes


def verify_target_hashes_unchanged(root: Path, before: Mapping[str, str]) -> list[str]:
    """Return list of target relative paths modified or deleted during PoC execution."""
    resolved_root = Path(root).resolve()
    tampered: list[str] = []
    for rel, expected_hash in before.items():
        target = resolved_root / rel
        if not target.is_file() or target.is_symlink():
            tampered.append(rel)
            continue
        try:
            actual_hash = _sha256(target.read_bytes())
        except OSError:
            tampered.append(rel)
            continue
        if actual_hash != expected_hash:
            tampered.append(rel)
    return tampered


